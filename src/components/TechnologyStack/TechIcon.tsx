// ─── Main TechIcon Component ────────────────────────────────────────────────
export interface TechIconProps {
  technology: Technology;
  className?: string;
  size?: number;
}

export const TechIcon: React.FC<TechIconProps> = ({
  technology,
  className = 'w-7 h-7',
  size = 28,
}) => {
  const { iconType, iconKey, iconColor, name } = technology;
  const brandColor = iconColor || '#B6FF00';

  // 1. Brand SVG Logo
  if (iconType === 'logo') {
    const renderSvg = BRAND_SVGS[iconKey.toLowerCase()];
    if (renderSvg) {
      return (
        <div className={`flex items-center justify-center shrink-0 ${className}`}>
          {renderSvg(brandColor)}
        </div>
      );
    }
  }

  // 2. Lucide Icon
  if (iconType === 'lucide' || (iconType === 'logo' && !BRAND_SVGS[iconKey.toLowerCase()])) {
    const LucideComponent = LUCIDE_MAP[iconKey] || Code;
    return (
      <div className={`flex items-center justify-center shrink-0 ${className}`}>
        <LucideComponent
          size={size}
          style={{ color: brandColor }}
          strokeWidth={1.8}
        />
      </div>
    );
  }

  // 3. Abbreviation / Conceptual Badge
  const badgeText = iconKey && iconKey.length <= 4 ? iconKey : name.slice(0, 2).toUpperCase();

  return (
    <div
      className={`flex items-center justify-center shrink-0 font-mono font-bold tracking-tight rounded-md border transition-all ${className}`}
      style={{
        backgroundColor: `${brandColor}15`,
        borderColor: `${brandColor}40`,
        color: brandColor,
        fontSize: badgeText.length > 2 ? '10px' : '12px',
      }}
    >
      {badgeText}
    </div>
  );
};

export default TechIcon;
